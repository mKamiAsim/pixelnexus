"""Write the dependencies and licenses table, from the installed packages.

Usage:
    uv run --extra cpu python tools/gen_licenses.py   # after pnpm install

The direct runtime dependencies come from engine/pyproject.toml and web/package.json. Each
version and license is read from the installed package's own metadata, so nothing is typed by
hand. Since it reads what is installed, CI does not check it; run it after changing dependencies.
"""

from __future__ import annotations

import json
import re
import tomllib
from importlib import metadata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "_generated" / "dependencies.md"


def python_license(name: str) -> tuple[str, str]:
    try:
        meta = metadata.metadata(name)
    except metadata.PackageNotFoundError:
        return "not installed", ""
    version = meta["Version"]
    expression = meta.get("License-Expression")
    if expression:
        return version, expression
    classifiers = [
        c.split(" :: ")[-1] for c in meta.get_all("Classifier") or [] if c.startswith("License ::")
    ]
    if classifiers:
        return version, ", ".join(classifiers)
    text = (meta.get("License") or "").strip()
    return version, text if text and len(text) < 60 else "see the package"


def python_rows() -> list[list[str]]:
    project = tomllib.loads((ROOT / "engine" / "pyproject.toml").read_text("utf-8"))["project"]
    groups = [("engine", project["dependencies"])]
    groups += [
        (f"engine, {extra} extra", deps)
        for extra, deps in project.get("optional-dependencies", {}).items()
    ]
    rows = []
    for where, deps in groups:
        for spec in deps:
            name = re.split(r"[\[<>=;! ]", spec, maxsplit=1)[0]
            version, license_text = python_license(name)
            rows.append([f"`{name}`", where, version, license_text])
    return rows


def web_rows() -> list[list[str]]:
    package = json.loads((ROOT / "web" / "package.json").read_text("utf-8"))
    rows = []
    for name in package["dependencies"]:
        installed = ROOT / "web" / "node_modules" / name / "package.json"
        if installed.exists():
            data = json.loads(installed.read_text("utf-8"))
            rows.append(
                [f"`{name}`", "studio", data.get("version", ""), str(data.get("license", ""))]
            )
        else:
            rows.append([f"`{name}`", "studio", "not installed", ""])
    return rows


def main() -> None:
    rows = web_rows() + python_rows()
    lines = [
        "<!-- Generated by tools/gen_licenses.py from the installed packages. Do not edit. -->",
        "",
        "| Package | Used by | Version | License |",
        "|---|---|---|---|",
        *(f"| {' | '.join(r)} |" for r in rows),
    ]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"Wrote {OUT.relative_to(ROOT)} with {len(rows)} packages.")


if __name__ == "__main__":
    main()
