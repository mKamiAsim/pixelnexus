"""Write the tiny ONNX model the engine runs to check that a device really works.

The model is one 3 x 3 convolution with fixed weights, saved with IR version 10 so that ONNX
Runtime 1.30 reads it. The engine keeps it as base64 in probe_model.py, so the engine never
needs the onnx package. Run with --check to verify the stored model is current.
"""

from __future__ import annotations

import argparse
import base64
import sys
from pathlib import Path

import numpy as np
from onnx import TensorProto, helper

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "engine" / "src" / "pixelnexus_engine" / "probe_model.py"
WIDTH = 96


def build() -> bytes:
    rng = np.random.default_rng(0)
    weights = rng.normal(size=(3, 3, 3, 3)).astype(np.float32)
    x = helper.make_tensor_value_info("x", TensorProto.FLOAT, [1, 3, None, None])
    y = helper.make_tensor_value_info("y", TensorProto.FLOAT, [1, 3, None, None])
    w = helper.make_tensor("w", TensorProto.FLOAT, [3, 3, 3, 3], weights.ravel().tolist())
    node = helper.make_node("Conv", ["x", "w"], ["y"], pads=[1, 1, 1, 1])
    graph = helper.make_graph([node], "probe", [x], [y], [w])
    model = helper.make_model(
        graph,
        opset_imports=[helper.make_opsetid("", 17)],
        ir_version=10,
        producer_name="pixelnexus",
    )
    data: bytes = model.SerializeToString()
    return data


def source() -> str:
    text = base64.b64encode(build()).decode("ascii")
    lines = [text[i : i + WIDTH] for i in range(0, len(text), WIDTH)]
    body = "\n".join(f'    "{line}"' for line in lines)
    return (
        '"""A tiny ONNX model, one 3 x 3 convolution, that checks a device works.\n\n'
        "Generated by tools/make_probe_model.py. Do not edit.\n"
        '"""\n\n'
        f"PROBE_ONNX_BASE64 = (\n{body}\n)\n"
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if the stored model is stale")
    args = parser.parse_args(argv)
    text = source()
    current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else None
    if args.check:
        if current != text:
            print("The probe model is out of date. Run tools/make_probe_model.py.")
            return 1
        print("The probe model is up to date.")
        return 0
    TARGET.write_text(text, encoding="utf-8", newline="\n")
    print(f"Wrote {TARGET.relative_to(ROOT)}.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
