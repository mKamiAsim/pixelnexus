"""Write generated Markdown fragments for the docs from the catalog.

Usage:
    uv run python tools/gen_docs.py          # write docs/_generated/*.md
    uv run python tools/gen_docs.py --check  # fail if the files are out of date

Pages include these fragments with pymdownx snippets, for example:
    --8<-- "catalog-status.md"

Only facts that can be read reliably from the catalog are generated. Explanations are written
by hand. For every filter with a docs page it also writes filters/<id>-<part>.md fragments:
facts, formula, steps, params, complexity, limits, tests and references. So the docs and the
Inspector read the same catalog text. Kernels and worked examples come from the filter code
through web/scripts/gen-filter-docs.mjs.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from collections import Counter
from typing import Any

from catalog_lib import ROOT, load_catalog

OUT_DIR = ROOT / "docs" / "_generated"
HEADER = "<!-- Generated by tools/gen_docs.py from catalog/. Do not edit. -->\n\n"
REPO_URL = "https://github.com/mKamiAsim/pixelnexus/blob/main/"
PLACEHOLDER = re.compile(r"\{\{\s*([a-zA-Z][a-zA-Z0-9]*)\s*\}\}")
LINE_BREAK = "\\\\"

STATUS_LABELS = {
    "implemented-tested": "Implemented and tested",
    "implemented-untested": "Implemented, testing incomplete",
    "partial": "Partially implemented",
    "optional-dependency": "Available through an optional dependency",
    "optional-model": "Available through an optional pretrained model",
    "planned": "Planned but not implemented",
    "unsupported": "Unsupported or deprecated",
}


def table(headers: list[str], rows: list[list[str]], align: list[str]) -> str:
    marks = {"left": "---", "right": "--:"}
    lines = ["| " + " | ".join(headers) + " |", "|" + "|".join(marks[a] for a in align) + "|"]
    lines += ["| " + " | ".join(row) + " |" for row in rows]
    return "\n".join(lines) + "\n"


def catalog_status(bundle: dict[str, Any]) -> str:
    entries = [*bundle["filters"], *bundle["tools"]]
    counts = Counter(entry["status"] for entry in entries)
    rows = [[label, str(counts[key])] for key, label in STATUS_LABELS.items() if counts[key]]
    rows.append(["**Total**", f"**{len(entries)}**"])
    return HEADER + table(["Status", "Entries"], rows, ["left", "right"])


def catalog_families(bundle: dict[str, Any]) -> str:
    counts = Counter(entry["family"] for entry in bundle["filters"])
    families = sorted(bundle["families"], key=lambda family: family["order"])
    rows = [[f["name"], str(counts[f["id"]]), f["description"]] for f in families]
    rows.append(["Selection tools", str(len(bundle["tools"])), "Tools that create selections."])
    return HEADER + table(["Family", "Entries", "What it covers"], rows, ["left", "right", "left"])


AI_INPUTS = {
    "image": "the image",
    "mask": "the selection",
    "points": "your clicks",
    "box": "the box you drew",
}


def ai_tasks(bundle: dict[str, Any]) -> str:
    """The AI router tasks with what they send and return, and their classical alternatives."""
    names = {("tool", e["id"]): e["name"] for e in bundle["tools"]} | {
        ("filter", e["id"]): e["name"] for e in bundle["filters"]
    }
    rows = []
    for task in bundle["aiTasks"]:
        parts = [AI_INPUTS[i] for i in task["inputs"]]
        sends = " and ".join([", ".join(parts[:-1]), parts[-1]]) if len(parts) > 1 else parts[0]
        sends = sends[0].upper() + sends[1:]
        if task["crop"]:
            sends += ". With a selection or a box, only that area plus a margin"
        classical = names[(task["classical"]["kind"], task["classical"]["id"])]
        returns = "A mask" if task["output"] == "mask" else "An image"
        model_names = {m["id"]: m["name"] for m in bundle["models"]}
        models = " or ".join(model_names.get(m, m) for m in task.get("models", []) or []) or "None"
        rows.append([task["name"], sends, returns, classical, models])
    headers = ["Task", "Sends", "Returns", "Classical alternative", "Models, the default first"]
    return HEADER + table(headers, rows, ["left", "left", "left", "left", "left"])


MODEL_FORMATS = {
    "onnx": "ONNX",
    "pytorch": "PyTorch, exported to ONNX once",
    "tensorflow-pb": "TensorFlow graph, run by OpenCV",
    "caffe": "Caffe, exported to ONNX once",
    "opencv-yml": "OpenCV model file",
}


def models_reference(bundle: dict[str, Any]) -> str:
    """Every approved model: format, size, where it runs, license, and who uses it."""
    users: dict[str, list[str]] = {}
    for task in bundle["aiTasks"]:
        for model in task.get("models", []) or []:
            users.setdefault(model, []).append(f"{task['name']} (AI task)")
    for entry in bundle["filters"]:
        named = [
            entry.get("model"),
            *((entry.get("modelChoices") or {}).get("models", {}) or {}).values(),
        ]
        for model in dict.fromkeys(m for m in named if m):
            users.setdefault(model, []).append(f"{entry['name']} (filter)")
    rows, facts = [], []
    for model in bundle["models"]:
        runs = model["runtimes"]
        if model["format"] != "onnx":
            runs = [r for r in runs if r != "on-device"]
        where = " and ".join({"engine": "engine", "on-device": "browser"}[r] for r in runs)
        license_text = model["license"].split(". ")[0].rstrip(".")
        if model.get("licenseUrl"):
            license_text = f"[{license_text}]({model['licenseUrl']})"
        if model.get("nonCommercial") and "commercial" not in license_text:
            license_text += ", non-commercial use only"
        rows.append(
            [
                model["name"],
                MODEL_FORMATS.get(model["format"], model["format"]),
                f"{model['sizeMB']} MB",
                where,
                "Yes" if model.get("phoneSuitable") else "No",
                license_text,
                ", ".join(users.get(model["id"], [])) or "None yet",
            ]
        )
        reference = model.get("reference") or {}
        paper = reference.get("text", "")
        if reference.get("doi"):
            paper += f" [DOI {reference['doi']}](https://doi.org/{reference['doi']})"
        elif reference.get("url"):
            paper += f" [{reference['url']}]({reference['url']})"
        facts.append(
            [model["name"], model.get("inputs", ""), model.get("outputs", ""), paper or "None"]
        )
    headers = ["Model", "Format", "Size", "Runs in", "Phone", "License", "Used by"]
    first = table(headers, rows, ["left", "left", "right", "left", "left", "left", "left"])
    second = table(["Model", "Takes", "Gives", "Paper"], facts, ["left"] * 4)
    return HEADER + first + "\n" + second


def _schema_type(spec: dict[str, Any], defs: dict[str, Any]) -> str:
    """A short type name for a schema property."""
    if "$ref" in spec:
        target = defs.get(spec["$ref"].split("/")[-1], {})
        if "enum" in target:
            return "one of " + ", ".join(f"`{v}`" for v in target["enum"])
        return str(target.get("title") or target.get("type") or spec["$ref"].split("/")[-1])
    if "enum" in spec:
        return "one of " + ", ".join(f"`{v}`" for v in spec["enum"])
    if spec.get("type") == "array":
        items = spec.get("items", {})
        return f"list of {_schema_type(items, defs)}" if items else "list"
    return str(spec.get("type", "any"))


def filter_schema() -> str:
    """Every field of a filter entry, from catalog/schema/catalog.schema.json."""
    schema = json.loads((ROOT / "catalog" / "schema" / "catalog.schema.json").read_text("utf-8"))
    defs = schema["$defs"]
    spec = defs["filter"]
    required = set(spec.get("required", []))
    rows = []
    for key, prop in spec["properties"].items():
        ref = defs.get(prop.get("$ref", "").split("/")[-1], {}) if "$ref" in prop else {}
        text = prop.get("description") or ref.get("description") or ""
        rows.append([f"`{key}`", "Yes" if key in required else "", _schema_type(prop, defs), text])
    return HEADER + table(["Field", "Required", "Type", "Meaning"], rows, ["left"] * 4)


def glossary(bundle: dict[str, Any]) -> str:
    """The glossary from catalog/glossary.yaml, the same text as the studio's tooltips."""
    rows = []
    for term in sorted(bundle["glossary"], key=lambda t: str(t["term"]).lower()):
        rows.append(
            [
                f"**{term['term']}**",
                ", ".join(term.get("aliases", []) or []),
                term["definition"],
                ", ".join(term.get("seeAlso", []) or []),
            ]
        )
    return HEADER + table(["Term", "Also called", "Meaning", "See also"], rows, ["left"] * 4)


def common_params(bundle: dict[str, Any]) -> str:
    """The shared parameters from catalog/common-params.yaml."""
    rows = []
    for p in bundle["commonParams"]:
        options = ", ".join(f"`{o['value']}` ({o['label']})" for o in p.get("options", []) or [])
        rows.append(
            [
                f"`{p['key']}`",
                p["label"],
                p["type"],
                f"`{p['default']}`",
                options,
                p["description"] + (f" {p['effect']}" if p.get("effect") else ""),
            ]
        )
    headers = ["Key", "Label", "Type", "Default", "Options", "Meaning"]
    return HEADER + table(headers, rows, ["left"] * 6)


def resolve_params(entry: dict[str, Any], common: dict[str, Any]) -> list[dict[str, Any]]:
    """Expand shared parameters. The channel scope offers only the scopes the filter allows."""
    params = []
    for raw in entry.get("params", []) or []:
        if "ref" in raw:
            shared = common[raw["ref"]]
            param = {**shared, **{k: v for k, v in raw.items() if k != "ref"}}
        else:
            param = raw
        allowed = entry.get("channelScopes")
        if param["key"] == "channelScope" and allowed:
            param = {**param, "options": [o for o in param["options"] if o["value"] in allowed]}
        params.append(param)
    return params


def tex_value(value: Any) -> str:
    if isinstance(value, bool):
        return r"\text{on}" if value else r"\text{off}"
    if isinstance(value, int | float):
        return f"{value:g}"
    return r"\text{" + str(value) + "}"


def display_math(tex: str) -> str:
    """A display formula that KaTeX and MathJax both render.

    MathJax breaks lines only inside an environment, so a formula with top-level line breaks
    is wrapped in "gathered". Line breaks inside "cases" stay where they are.
    """
    body = tex.strip()
    outside_cases = re.sub(r"\\begin\{cases\}.*?\\end\{cases\}", "", body, flags=re.S)
    if LINE_BREAK in outside_cases:
        body = "\\begin{gathered}\n" + body + "\n\\end{gathered}"
    return "\\[\n" + body + "\n\\]\n"


def label_of(value: Any, param: dict[str, Any]) -> str:
    for option in param.get("options", []) or []:
        if option["value"] == value:
            return str(option["label"])
    if isinstance(value, bool):
        return "on" if value else "off"
    return f"{value:g}" if isinstance(value, int | float) else str(value)


def value_rule(param: dict[str, Any]) -> str:
    if param["type"] in ("number", "integer", "angle"):
        rule = f"{param['min']:g} to {param['max']:g}"
        if param.get("oddOnly"):
            rule += ", odd"
        if param.get("unit"):
            rule += f" {param['unit']}"
        return rule
    if param["type"] == "select":
        return ", ".join(str(option["label"]) for option in param["options"])
    if param["type"] == "kernel":
        return "Rows of numbers, odd sides up to 15"
    if param["type"] == "structuring-element":
        return "Disk, rectangle, ellipse, cross, diamond, line or custom, with sizes"
    if param["type"] == "image":
        return "This image, or another open image of the same size"
    if param["type"] == "points":
        return "Pairs fx fy from -0.5 to 0.5 cycles/px, up to 32"
    return "On or off" if param["type"] == "boolean" else str(param["type"])


def filter_fragments(entry: dict[str, Any], bundle: dict[str, Any]) -> dict[str, str]:
    common = {p["key"]: p for p in bundle["commonParams"]}
    families = {f["id"]: f["name"] for f in bundle["families"]}
    params = resolve_params(entry, common)
    defaults = {p["key"]: p["default"] for p in params}
    cls = entry["classification"]
    impl = entry["implementation"]
    source = entry.get("representationSource") or impl
    family = families.get(entry["family"], entry["family"])
    also = ", ".join(families.get(f, f) for f in entry.get("alsoIn", []) or [])

    facts = [
        ["Status", STATUS_LABELS[entry["status"]]],
        ["Family", family + (f" (also {also})" if also else "")],
        ["Engine", "Browser" if entry["engine"] == "browser" else "Science engine"],
        ["Type", f"{cls['linearity'].capitalize()}, {cls['domain']}, {cls['operation']}"],
        ["Output", str(entry["output"]).capitalize()],
        ["Operator shown as", f"{entry['representation']} ({entry['representationLabel']})"],
        ["Support radius", f"`{entry['supportRadius']}`"],
        ["Code", f"[`{impl['path']}`]({REPO_URL}{impl['path']}), `{impl['symbol']}`"],
        ["Operator code", f"`{source['path']}`, `{source['symbol']}`"],
    ]
    if entry.get("aliases"):
        facts.insert(0, ["Also called", ", ".join(entry["aliases"])])
    if entry.get("dependencies"):
        packages = [
            d["name"] + (" (optional)" if d["optional"] else "") for d in entry["dependencies"]
        ]
        facts.append(["Packages", ", ".join(packages)])
    if entry.get("channelScopes"):
        scopes = {o["value"]: o["label"] for o in common["channelScope"]["options"]}
        facts.append(["Channels", ", ".join(scopes[s] for s in entry["channelScopes"])])

    out: dict[str, str] = {"facts": table(["Fact", "Value"], facts, ["left", "left"])}

    formula = PLACEHOLDER.sub(lambda m: tex_value(defaults.get(m.group(1), "?")), entry["formula"])
    symbols = "\n".join(f"- \\({s['symbol']}\\): {s['meaning']}" for s in entry["symbols"])
    explanation = entry.get("formulaExplanation", "")
    out["formula"] = (
        display_math(formula)
        + "\nThe formula shows the default parameter values.\n\nwhere\n\n"
        + symbols
        + "\n"
        + (f"\n{explanation}\n" if explanation else "")
    )
    out["steps"] = "\n".join(f"{i}. {step}" for i, step in enumerate(entry["steps"], 1)) + "\n"

    rows = [
        [
            f"**{p['label']}** `{p['key']}`",
            label_of(p["default"], p),
            value_rule(p),
            p["description"],
        ]
        for p in params
    ]
    out["params"] = table(
        ["Parameter", "Default", "Values", "Meaning"], rows, ["left", "left", "left", "left"]
    )

    complexity = entry["complexity"]
    notes = complexity.get("notes")
    out["complexity"] = (
        f"- Time: \\({complexity['time']}\\)\n- Memory: \\({complexity['memory']}\\)\n"
        + (f"\n{notes}\n" if notes else "")
    )
    limits = "\n".join(f"- {item}" for item in entry["limitations"])
    artifacts = "\n".join(f"- {item}" for item in entry.get("artifacts", []) or [])
    out["limits"] = (
        "**Limitations**\n\n"
        + limits
        + "\n"
        + (f"\n**Artifacts**\n\n{artifacts}\n" if artifacts else "")
    )
    out["tests"] = "\n".join(f"- [`{t}`]({REPO_URL}{t})" for t in entry["tests"]) + "\n"

    out["references"] = references_list(entry)
    return {f"filters/{entry['id']}-{part}.md": HEADER + text for part, text in out.items()}


GROUP_LABELS = {
    "marquee": "Marquee",
    "lasso": "Lasso",
    "brush": "Brush",
    "color": "Color and tone",
    "auto": "Automatic",
    "ai": "AI",
}


def references_list(entry: dict[str, Any]) -> str:
    references = []
    for ref in entry.get("references", []) or []:
        text = " ".join(ref["text"].split())
        if ref.get("url"):
            text += f" <{ref['url']}>"
        if ref.get("doi"):
            text += f" DOI [{ref['doi']}](https://doi.org/{ref['doi']})."
        references.append(f"- {text}")
    return "\n".join(references) + "\n"


def tool_fragments(entry: dict[str, Any], bundle: dict[str, Any]) -> dict[str, str]:
    """Facts, parameters, steps, tests and references of a selection tool."""
    common = {p["key"]: p for p in bundle["commonParams"]}
    params = resolve_params(entry, common)
    impl = entry["implementation"]
    facts = [
        ["Status", STATUS_LABELS[entry["status"]]],
        ["Group", GROUP_LABELS.get(entry["group"], entry["group"])],
        ["Engine", "Browser" if entry["engine"] == "browser" else "Science engine"],
        ["Code", f"[`{impl['path']}`]({REPO_URL}{impl['path']}), `{impl['symbol']}`"],
    ]
    if entry.get("aliases"):
        facts.insert(0, ["Also called", ", ".join(entry["aliases"])])
    out: dict[str, str] = {"facts": table(["Fact", "Value"], facts, ["left", "left"])}
    if params:
        rows = [
            [
                f"**{p['label']}** `{p['key']}`",
                label_of(p["default"], p),
                value_rule(p),
                p["description"],
            ]
            for p in params
        ]
        out["params"] = table(
            ["Parameter", "Default", "Values", "Meaning"], rows, ["left", "left", "left", "left"]
        )
    else:
        out["params"] = "This tool has no settings.\n"
    out["steps"] = "\n".join(f"{i}. {step}" for i, step in enumerate(entry["steps"], 1)) + "\n"
    out["tests"] = "\n".join(f"- [`{t}`]({REPO_URL}{t})" for t in entry["tests"]) + "\n"
    if entry.get("references"):
        out["references"] = references_list(entry)
    return {f"tools/{entry['id']}-{part}.md": HEADER + text for part, text in out.items()}


def tools_index(bundle: dict[str, Any]) -> str:
    """Every selection tool with a docs page, for docs/selection/index.md."""
    order = list(GROUP_LABELS)
    entries = [e for e in bundle["tools"] if e.get("docsPage")]
    entries.sort(key=lambda e: (order.index(e["group"]) if e["group"] in order else 99, e["name"]))
    rows = [
        [
            f"[{e['name']}]({e['docsPage'].removeprefix('selection/')})",
            GROUP_LABELS.get(e["group"], e["group"]),
            e.get("summary", ""),
            STATUS_LABELS[e["status"]],
        ]
        for e in entries
    ]
    headers = ["Tool", "Group", "What it does", "Status"]
    return HEADER + table(headers, rows, ["left", "left", "left", "left"])


def filters_index(bundle: dict[str, Any]) -> str:
    """Every filter with a docs page, for docs/filters/index.md. Links are relative to it."""
    families = {f["id"]: f for f in bundle["families"]}
    entries = [e for e in bundle["filters"] if e.get("docsPage")]
    entries.sort(key=lambda e: (families[e["family"]]["order"], e["name"]))
    rows = [
        [
            f"[{e['name']}]({e['docsPage'].removeprefix('filters/')})",
            families[e["family"]]["name"],
            e.get("summary", ""),
            STATUS_LABELS[e["status"]],
        ]
        for e in entries
    ]
    headers = ["Filter", "Family", "What it does", "Status"]
    return HEADER + table(headers, rows, ["left", "left", "left", "left"])


def build() -> dict[str, str]:
    bundle = load_catalog().bundle
    files = {
        "catalog-status.md": catalog_status(bundle),
        "catalog-families.md": catalog_families(bundle),
        "filters-index.md": filters_index(bundle),
        "tools-index.md": tools_index(bundle),
        "ai-tasks.md": ai_tasks(bundle),
        "models.md": models_reference(bundle),
        "filter-schema.md": filter_schema(),
        "glossary.md": glossary(bundle),
        "common-params.md": common_params(bundle),
    }
    for entry in bundle["filters"]:
        if entry.get("docsPage") and entry.get("formula"):
            files.update(filter_fragments(entry, bundle))
    for entry in bundle["tools"]:
        if entry.get("docsPage"):
            files.update(tool_fragments(entry, bundle))
    return files


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if files are out of date")
    args = parser.parse_args(argv)

    stale = []
    for name, text in build().items():
        path = OUT_DIR / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                stale.append(name)
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="\n")
    if stale:
        print("Out of date: " + ", ".join(stale) + ". Run tools/gen_docs.py.")
        return 1
    print("Generated docs are up to date." if args.check else f"Wrote {OUT_DIR}.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
